const squash = s => s.toLowerCase().replace(/[^a-z0-9]/g, '');
// Every word that should find something, so typing one is never cut short as a keyword like "and".
export const SPELLINGS = Object.entries(NAMES).flatMap(([n, [long, , also = []]]) => [
  n,
  squash(long),
  ...also.map(squash),
]);
/* How well a typed word finds a name: 0 for the name itself, 1 for its long name, 2 for another name; null
   for no match. The long name is shown when it was the one being typed. */
export function nameMatch(name, typed) {
  const q = squash(typed),
    [long, , also = []] = NAMES[name] || [name];
  if (!q) return null;
  if (name.toLowerCase().startsWith(q)) return { rank: 0, label: name };
  if (squash(long).startsWith(q)) return { rank: 1, label: long };
  const other = also.find(a => squash(a).startsWith(q));
  return other ? { rank: 2, label: long } : null;
}
